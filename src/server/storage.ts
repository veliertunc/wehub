import "server-only";

import { mkdir, rm } from "node:fs/promises";
import path from "node:path";

import { env } from "~/env";

export const UPLOAD_ROOT = path.resolve(process.cwd(), env.UPLOAD_DIR);
export const VIDEO_DIR = path.join(UPLOAD_ROOT, "videos");
export const THUMB_DIR = path.join(UPLOAD_ROOT, "thumbnails");

export const MAX_UPLOAD_BYTES = env.MAX_UPLOAD_MB * 1024 * 1024;
export const MAX_THUMB_BYTES = 5 * 1024 * 1024;

const MIME_EXT: Record<string, string> = {
  "video/mp4": ".mp4",
  "video/webm": ".webm",
  "video/ogg": ".ogv",
  "video/quicktime": ".mov",
  "video/x-matroska": ".mkv",
  "video/x-msvideo": ".avi",
  "video/mpeg": ".mpeg",
  "video/3gpp": ".3gp",
};

export const ALLOWED_VIDEO_TYPES = Object.keys(MIME_EXT);

export function extensionFor(mimeType: string, originalName?: string) {
  const fromName = originalName ? path.extname(originalName).toLowerCase() : "";
  if (/^\.[a-z0-9]{1,5}$/.test(fromName)) return fromName;
  return MIME_EXT[mimeType] ?? ".bin";
}

/** Ids are generated by us (base64url) — still guard against traversal. */
function assertSafeId(id: string) {
  if (!/^[A-Za-z0-9_-]+$/.test(id)) throw new Error("Invalid id");
}

export function videoPath(fileName: string) {
  const resolved = path.join(VIDEO_DIR, path.basename(fileName));
  return resolved;
}

export function thumbnailPath(videoId: string) {
  assertSafeId(videoId);
  return path.join(THUMB_DIR, `${videoId}.jpg`);
}

export async function ensureUploadDirs() {
  await mkdir(VIDEO_DIR, { recursive: true });
  await mkdir(THUMB_DIR, { recursive: true });
}

export async function deleteVideoFiles(
  videoId: string,
  fileName: string | null,
) {
  await Promise.all([
    fileName ? rm(videoPath(fileName), { force: true }) : Promise.resolve(),
    rm(thumbnailPath(videoId), { force: true }),
  ]);
}
